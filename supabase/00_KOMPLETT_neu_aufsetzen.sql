-- ─── Abschnitt: 01_schema.sql ───
-- LagerPal → Supabase (PostgreSQL)
-- Phase 1: Schema. In Supabase über den SQL-Editor ausführen.
-- LagerPal hat ein EIGENES Projekt → Tabellen liegen im Standard-Schema "public".

-- ── Artikel ──────────────────────────────────────────────────────────────────
create table if not exists artikel (
    artikelnummer text primary key,
    artikelname   text     not null default '',
    gtin          text     not null default '',
    ist_set       smallint not null default 0,   -- 0/1
    online        smallint not null default 0    -- 0=unbekannt, 1=online, 2=nicht online
);
create index if not exists idx_artikel_gtin on artikel(gtin);

-- ── Bestände (Menge je Artikel + Lagerplatz/Karton) ─────────────────────────
create table if not exists bestaende (
    artikelnummer text    not null references artikel(artikelnummer),
    lagerplatz    text    not null,
    menge         integer not null default 0,
    primary key (artikelnummer, lagerplatz)
);
create index if not exists idx_bestaende_artnr on bestaende(artikelnummer);
create index if not exists idx_bestaende_lp    on bestaende(lagerplatz);

-- ── Lagerplätze / Kartons (Metadaten: Palette + Kanal) ──────────────────────
create table if not exists lagerplaetze (
    name     text     primary key,
    angelegt text     not null default '',
    palette  text     not null default '',       -- gehört auf diese Palette ('' = keine)
    kanal    smallint not null default 0          -- 0=gemischt/unbestimmt, 1=online, 2=nicht online
);

-- ── Buchungen (Protokoll) ────────────────────────────────────────────────────
-- Hinweis: artikelnummer kann Platzhalter '—' enthalten (z. B. Lagerplatz-Ereignisse),
-- deshalb bewusst KEIN Fremdschlüssel auf artikel.
create table if not exists buchungen (
    id                     bigint generated by default as identity primary key,
    zeitstempel            timestamptz not null,
    typ                    text        not null,
    artikelnummer          text        not null,
    artikelname            text,
    gtin                   text,
    lagerplatz             text,
    menge                  integer,
    bestand_lp_vorher      integer,
    bestand_lp_nachher     integer,
    bestand_gesamt_vorher  integer,
    bestand_gesamt_nachher integer,
    kommentar              text,
    rueckgaengig_gemacht   smallint not null default 0
);
create index if not exists idx_buchungen_zeit on buchungen(zeitstempel);
-- Vorgang: gleiche Kennung = Teile EINER Aktion (z. B. Umlagerung + Inventur-Zugang
-- eines Einräum-Scans, alle Plätze eines Sammel-Ausbuchens). Rückgängig nimmt
-- immer den ganzen Vorgang zurück. (Paket 2, Stand 10/2026)
alter table buchungen add column if not exists vorgang uuid;
create index if not exists idx_buchungen_vorgang on buchungen(vorgang) where vorgang is not null;
create index if not exists idx_buchungen_typ  on buchungen(typ);

-- ── Leermeldungen (Glocke) ───────────────────────────────────────────────────
create table if not exists leermeldungen (
    id            bigint generated by default as identity primary key,
    zeitstempel   timestamptz not null,
    artikelnummer text    not null,
    artikelname   text,
    gtin          text,
    lagerplatz    text    not null,
    gesehen       smallint not null default 0,
    hinweis       text    not null default ''
);
create index if not exists idx_leer_offen on leermeldungen(gesehen);
-- Höchstens EINE offene Meldung je Artikel + Platz (zwei Geräte gleichzeitig
-- konnten sonst beide eine anlegen). Bestehende Doppelte vorher auf „gesehen".
-- Alle Einfügungen nutzen „on conflict do nothing". (Paket 2, Stand 10/2026)
update leermeldungen l set gesehen = 1
    where gesehen = 0 and artikelnummer <> '—'
      and exists (select 1 from leermeldungen k where k.gesehen = 0 and k.artikelnummer = l.artikelnummer
                  and k.lagerplatz = l.lagerplatz and k.id < l.id);
create unique index if not exists uq_leer_offen on leermeldungen(artikelnummer, lagerplatz)
    where gesehen = 0 and artikelnummer <> '—';

-- ── CHECK-Constraints (Paket 2) ──────────────────────────────────────────────
-- Die Datenbank selbst verhindert negative Bestände und ungültige Kennzeichen —
-- egal, ob über eine Funktion oder direkt per REST geschrieben wird. Passend
-- dazu schreiben buchen()/rueckgaengig()/bestand_csv_import() in 05_functions.sql
-- konditional (WHERE ... menge >= x), damit statt einer technischen
-- Constraint-Fehlermeldung weiterhin die gewohnte Meldung erscheint.
alter table bestaende     drop constraint if exists bestaende_menge_nicht_negativ;
alter table bestaende     add  constraint bestaende_menge_nicht_negativ   check (menge >= 0);
alter table artikel       drop constraint if exists artikel_ist_set_gueltig;
alter table artikel       add  constraint artikel_ist_set_gueltig         check (ist_set in (0,1));
alter table artikel       drop constraint if exists artikel_online_gueltig;
alter table artikel       add  constraint artikel_online_gueltig          check (online in (0,1,2));
alter table lagerplaetze  drop constraint if exists lagerplaetze_kanal_gueltig;
alter table lagerplaetze  add  constraint lagerplaetze_kanal_gueltig      check (kanal in (0,1,2));
alter table leermeldungen drop constraint if exists leermeldungen_gesehen_gueltig;
alter table leermeldungen add  constraint leermeldungen_gesehen_gueltig   check (gesehen in (0,1));
alter table buchungen     drop constraint if exists buchungen_rueckgaengig_gueltig;
alter table buchungen     add  constraint buchungen_rueckgaengig_gueltig  check (rueckgaengig_gemacht in (0,1));

-- ── Unbekannte Artikel (Paket A, Stand 28.09.2026) ───────────────────────────
-- unbekannt = 1: Platzhalter, automatisch angelegt beim Scannen einer EAN, die
-- es in LagerPal noch nicht gibt (Artikelnummer WE-0-230, WE-0-231, …, Name
-- „Unbekannt 1", „Unbekannt 2", …). Solche Artikel landen immer im aktuellen
-- Klärfall-Karton „Unbekannt-NN" und werden NICHT in die JTL-Exporte
-- geschrieben, bis sie im Büro einem echten Artikel zugeordnet sind (Paket B).
alter table artikel add column if not exists unbekannt smallint not null default 0;
alter table artikel drop constraint if exists artikel_unbekannt_gueltig;
alter table artikel add  constraint artikel_unbekannt_gueltig check (unbekannt in (0,1));
-- für die Suche nach der höchsten bisher vergebenen WE-0-Nummer im Protokoll
create index if not exists idx_buchungen_we on buchungen(artikelnummer) where artikelnummer like 'WE-0-%';

-- ── JTL-Artikelliste (Nachschlage-Tabelle, Stand 28.09.2026) ─────────────────
-- Kompletter Artikelstamm aus JTL („Alle WUN die es jemals gab.csv"), OHNE
-- Set-Artikel (Nummern mit Endung -S2, -S3 …). Wird nur zum Nachschlagen beim
-- Scannen benutzt: Ist eine gescannte EAN in LagerPal unbekannt, steht aber
-- genau EINMAL in dieser Liste, legt artikel_aus_liste() den echten Artikel
-- (JTL-Nummer + Name, nicht online) an. Taucht sonst nirgends auf (Suche,
-- Dashboard, Export, Backup). Quelle/Neuaufbau: 21b_jtl_artikelliste_daten.sql.
create table if not exists jtl_artikelliste (
    artikelnummer text primary key,
    artikelname   text not null default '',
    gtin          text not null default ''
);
create index if not exists idx_jtl_liste_gtin on jtl_artikelliste(gtin) where gtin <> '';


-- ─── Abschnitt: 03_rls_policies.sql ───
-- LagerPal → Supabase · Phase 2: Sicherheitsregeln (RLS)
-- Modell (Stand Paket 3): angemeldete Nutzer (Rolle "authenticated") dürfen
-- alle Tabellen NUR LESEN; geschrieben wird ausschließlich über die
-- SECURITY-DEFINER-Funktionen aus 05_functions.sql/08_paletten.sql (buchen,
-- umlagern, artikel_neu, …) - die sind damit die einzige "Tür" zum Schreiben,
-- direkte Änderungen per REST (absichtlich oder durch einen Frontend-Fehler)
-- werden von der Datenbank abgewiesen. Nicht angemeldete (Rolle "anon")
-- dürfen weiterhin gar nichts.
-- Im SQL-Editor ausführen, nachdem Schema + Daten (01, 02) geladen sind.

-- 1) RLS auf allen Tabellen einschalten (idempotent)
alter table artikel        enable row level security;
alter table bestaende      enable row level security;
alter table lagerplaetze   enable row level security;
alter table buchungen      enable row level security;
alter table leermeldungen  enable row level security;

-- 2) Nur Lese-Policy für angemeldete Nutzer, pro Tabelle. Schreibrechte werden
--    per REVOKE zusätzlich auf Tabellenebene entzogen (siehe unten) - die
--    SECURITY-DEFINER-Funktionen umgehen das, weil sie mit den Rechten ihres
--    Besitzers laufen, nicht mit denen des aufrufenden Nutzers.
drop policy if exists "auth_read_artikel" on artikel;
create policy "auth_read_artikel"       on artikel       for select to authenticated using (true);
drop policy if exists "auth_read_bestaende" on bestaende;
create policy "auth_read_bestaende"     on bestaende     for select to authenticated using (true);
drop policy if exists "auth_read_lagerplaetze" on lagerplaetze;
create policy "auth_read_lagerplaetze"  on lagerplaetze  for select to authenticated using (true);
drop policy if exists "auth_read_buchungen" on buchungen;
create policy "auth_read_buchungen"     on buchungen     for select to authenticated using (true);
drop policy if exists "auth_read_leermeldungen" on leermeldungen;
create policy "auth_read_leermeldungen" on leermeldungen for select to authenticated using (true);

-- Für "anon" (nicht angemeldet) gibt es KEINE Policy → automatisch gesperrt. Das ist gewollt.

-- 3) Direkte Schreibrechte auf Tabellenebene entziehen (die Policy oben deckt
--    nur SELECT ab, aber ohne dieses REVOKE dürfte "authenticated" per
--    Tabellen-Grant trotzdem schreiben - RLS und GRANT/REVOKE wirken zusammen).
revoke insert, update, delete, truncate, references, trigger on artikel, bestaende, lagerplaetze, buchungen, leermeldungen from anon, authenticated;
revoke all on artikel, bestaende, lagerplaetze, buchungen, leermeldungen from anon;
grant select on artikel, bestaende, lagerplaetze, buchungen, leermeldungen to authenticated;

-- (Sichten: nur-lesen-Rechte stehen am Ende von 04_views.sql, weil die Sichten
--  erst dort angelegt werden - hier würde das Neu-Aufsetzen sonst mit
--  "relation v_lagerplaetze does not exist" abbrechen.)

-- 4) Nutzer dürfen im Schema public keine eigenen Objekte anlegen (verhindert
--    u.a., dass eine gleichnamige Tabelle untergeschoben wird, siehe Kommentar
--    zu den pg_temp.-qualifizierten Hilfstabellen in bestand_csv_import).
revoke create on schema public from anon, authenticated;

-- JTL-Artikelliste (Nachschlage-Tabelle): nur lesen, schreiben nur per SQL-Editor
alter table jtl_artikelliste enable row level security;
drop policy if exists "auth_read_jtl_artikelliste" on jtl_artikelliste;
create policy "auth_read_jtl_artikelliste" on jtl_artikelliste for select to authenticated using (true);
revoke all on jtl_artikelliste from anon;
revoke insert, update, delete, truncate, references, trigger on jtl_artikelliste from authenticated;
grant select on jtl_artikelliste to authenticated;


-- ─── Abschnitt: 04_views.sql ───
-- LagerPal → Supabase · Phase 3: Sichten (Views) für korrekte Aggregation.
-- Grund: die Supabase-API liefert pro Abfrage max. ~1000 Zeilen; Summen/Zählungen
-- über die ganze Tabelle macht deshalb die Datenbank in einer View.
-- security_invoker = true → die RLS der zugrunde liegenden Tabellen greift weiter
-- (nur angemeldete Nutzer sehen etwas).

-- Lagerplätze/Kartons: je Platz Artikel-Anzahl + Stück, plus Palette/Kanal.
create or replace view v_lagerplaetze
with (security_invoker = true) as
select
  coalesce(b.lagerplatz, lp.name) as name,
  coalesce(b.artikel, 0)          as artikel,
  coalesce(b.stueck, 0)           as stueck,
  coalesce(lp.palette, '')        as palette,
  coalesce(lp.kanal, 0)           as kanal
from (
  select lagerplatz, count(*) as artikel, sum(menge) as stueck
  from bestaende where menge > 0 group by lagerplatz
) b
full outer join lagerplaetze lp on lp.name = b.lagerplatz;

revoke all on v_lagerplaetze from anon;
grant select on v_lagerplaetze to authenticated;

-- Dashboard-Kennzahlen: eine einzige Zeile (Summen/Zählungen macht die DB).
-- Tages-/Wochenbeginn nach deutscher Zeit (Supabase rechnet sonst in UTC →
-- zwischen 0 und 2 Uhr zählte "heute" falsch). Als Zeitpunkt statt ::date,
-- damit der Index auf buchungen.zeitstempel genutzt werden kann.
create or replace view v_dashboard
with (security_invoker = true) as
with grenzen as (
  select date_trunc('day',  now() at time zone 'Europe/Berlin') at time zone 'Europe/Berlin' as tag_beginn,
         date_trunc('week', now() at time zone 'Europe/Berlin') at time zone 'Europe/Berlin' as woche_beginn
)
select
  (select count(*) from artikel)                                             as artikel_gesamt,
  (select coalesce(sum(menge),0) from bestaende)                             as bestand_gesamt,
  (select count(distinct lagerplatz) from bestaende where menge>0)           as lp_mit_bestand,
  (select count(*) from (select lagerplatz from bestaende where menge>0
                         union select name from lagerplaetze) t)             as lp_gesamt,
  (select count(*) from artikel where ist_set=1)                             as set_artikel,
  (select count(*) from artikel a where not exists
     (select 1 from bestaende b where b.artikelnummer=a.artikelnummer and b.menge>0)) as artikel_ohne_bestand,
  (select count(*) from leermeldungen where gesehen=0)                       as leermeldungen_offen,
  (select count(*) from (select gtin from artikel where gtin<>''
                         group by gtin having count(*)>1) g)                 as gtin_mehrdeutig,
  (select count(*) from artikel where online=2)                             as nicht_online,
  (select count(*) from artikel where online=0)                             as online_unbekannt,
  (select coalesce(sum(menge),0) from buchungen
     where typ='Eingang' and rueckgaengig_gemacht=0 and kommentar is distinct from 'Inventur-Zugang (Einräumen)'
       and zeitstempel >= (select tag_beginn from grenzen)) as ein_heute,
  (select coalesce(sum(menge),0) from buchungen
     where typ='Ausgang' and rueckgaengig_gemacht=0 and zeitstempel >= (select tag_beginn from grenzen)) as aus_heute,
  (select coalesce(sum(menge),0) from buchungen
     where typ='Eingang' and rueckgaengig_gemacht=0 and kommentar is distinct from 'Inventur-Zugang (Einräumen)'
       and zeitstempel >= (select woche_beginn from grenzen)) as ein_woche,
  (select coalesce(sum(menge),0) from buchungen
     where typ='Ausgang' and rueckgaengig_gemacht=0 and zeitstempel >= (select woche_beginn from grenzen)) as aus_woche;

revoke all on v_dashboard from anon;
grant select on v_dashboard to authenticated;

-- Sichten: nur lesen (Paket 3). Steht hier und nicht in 03_rls_policies.sql,
-- weil die Sichten erst in dieser Datei angelegt werden.
revoke insert, update, delete, truncate, references, trigger on v_lagerplaetze, v_dashboard from anon, authenticated;
grant select on v_lagerplaetze, v_dashboard to authenticated;


-- ─── Abschnitt: 05_functions.sql ───
-- LagerPal → Supabase · Phase 3: Schreib-Funktionen (transaktionssicher)
-- Eine Funktion läuft in EINER Transaktion → alles-oder-nichts.
-- Aufruf aus der Web-App: supabase.rpc('buchen', { p_artikelnummer:…, … })

-- ── Ein-/Ausbuchen ───────────────────────────────────────────────────────────
create or replace function buchen(
    p_artikelnummer text,
    p_lagerplatz    text,
    p_typ           text,              -- 'ein' | 'aus'
    p_menge         integer,
    p_kommentar     text default ''
) returns jsonb
language plpgsql security definer set search_path = public, pg_temp
as $$
declare
    v_name  text;
    v_gtin  text;
    v_delta integer;
    v_lp_vorher      integer;
    v_lp_nachher     integer;
    v_gesamt_vorher  integer;
    v_gesamt_nachher integer;
begin
    if p_typ not in ('ein','aus') then raise exception 'Ungültiger Typ'; end if;
    if p_menge is null or p_menge <= 0 then raise exception 'Menge muss eine positive ganze Zahl sein'; end if;

    select artikelname, gtin into v_name, v_gtin from artikel where artikelnummer = p_artikelnummer;
    if not found then raise exception 'Artikel % nicht gefunden', p_artikelnummer; end if;

    v_delta := case when p_typ = 'ein' then p_menge else -p_menge end;

    if p_typ = 'ein' then
        -- Bestand am Platz atomar erhöhen (race-sicher, kein Lost-Update)
        insert into bestaende (artikelnummer, lagerplatz, menge)
            values (p_artikelnummer, p_lagerplatz, p_menge)
            on conflict (artikelnummer, lagerplatz)
            do update set menge = bestaende.menge + p_menge
            returning menge into v_lp_nachher;
    else
        -- nur abziehen, wenn genug da ist; die Bedingung wird unter Zeilensperre
        -- ausgewertet, zwei gleichzeitige Ausgänge können also nicht beide durchgehen
        update bestaende set menge = menge - p_menge
            where artikelnummer = p_artikelnummer and lagerplatz = p_lagerplatz and menge >= p_menge
            returning menge into v_lp_nachher;
        if not found then
            select menge into v_lp_vorher from bestaende
                where artikelnummer = p_artikelnummer and lagerplatz = p_lagerplatz;
            raise exception 'Bestand auf % würde negativ (aktuell: %)', p_lagerplatz, coalesce(v_lp_vorher, 0);
        end if;
    end if;
    v_lp_vorher := v_lp_nachher - v_delta;

    select coalesce(sum(menge),0) into v_gesamt_nachher from bestaende where artikelnummer = p_artikelnummer;
    v_gesamt_vorher := v_gesamt_nachher - v_delta;

    insert into buchungen (zeitstempel, typ, artikelnummer, artikelname, gtin, lagerplatz, menge,
        bestand_lp_vorher, bestand_lp_nachher, bestand_gesamt_vorher, bestand_gesamt_nachher, kommentar)
        values (now(), case when p_typ='ein' then 'Eingang' else 'Ausgang' end,
            p_artikelnummer, v_name, v_gtin, p_lagerplatz, p_menge,
            v_lp_vorher, v_lp_nachher, v_gesamt_vorher, v_gesamt_nachher, p_kommentar);

    -- Glocke pflegen: leer geworden → melden (nur wenn keine offene Meldung existiert)
    if v_lp_vorher > 0 and v_lp_nachher = 0 then
        if not exists (select 1 from leermeldungen
                       where artikelnummer = p_artikelnummer and lagerplatz = p_lagerplatz and gesehen = 0) then
            insert into leermeldungen (zeitstempel, artikelnummer, artikelname, gtin, lagerplatz, gesehen, hinweis)
                values (now(), p_artikelnummer, v_name, v_gtin, p_lagerplatz, 0, '') on conflict do nothing;
        end if;
    end if;
    -- wieder aufgefüllt → offene Meldung entfernen
    if p_typ = 'ein' and v_lp_nachher > 0 then
        delete from leermeldungen
            where artikelnummer = p_artikelnummer and lagerplatz = p_lagerplatz and gesehen = 0;
    end if;

    return jsonb_build_object('ok', true,
        'lp_bestand_neu', v_lp_nachher, 'bestand_gesamt_neu', v_gesamt_nachher,
        'artikelname', v_name);
end;
$$;
revoke all on function buchen(text,text,text,integer,text) from anon, public;
grant execute on function buchen(text,text,text,integer,text) to authenticated;

-- ── Umlagern (Bestand von Platz zu Platz) ────────────────────────────────────
create or replace function umlagern(
    p_artikelnummer text,
    p_von           text,
    p_nach          text,
    p_menge         integer
) returns jsonb
language plpgsql security definer set search_path = public, pg_temp
as $$
declare
    v_name text; v_gtin text;
    v_von_vorher  integer;
    v_von_nachher integer;
    v_nach_nachher integer;
begin
    if p_menge is null or p_menge <= 0 then raise exception 'Menge muss eine positive ganze Zahl sein'; end if;
    if p_von = p_nach then raise exception 'Quelle und Ziel sind identisch'; end if;

    select artikelname, gtin into v_name, v_gtin from artikel where artikelnummer = p_artikelnummer;
    if not found then raise exception 'Artikel % nicht gefunden', p_artikelnummer; end if;

    select menge into v_von_vorher from bestaende
        where artikelnummer = p_artikelnummer and lagerplatz = p_von for update;
    if not found then v_von_vorher := 0; end if;
    if v_von_vorher < p_menge then
        raise exception 'Auf % liegen nur % Stk', p_von, v_von_vorher;
    end if;

    -- Ziel atomar erhöhen
    insert into bestaende (artikelnummer, lagerplatz, menge) values (p_artikelnummer, p_nach, p_menge)
        on conflict (artikelnummer, lagerplatz) do update set menge = bestaende.menge + p_menge
        returning menge into v_nach_nachher;

    -- Quelle verringern
    update bestaende set menge = menge - p_menge
        where artikelnummer = p_artikelnummer and lagerplatz = p_von
        returning menge into v_von_nachher;

    -- Glocke pflegen
    if v_von_vorher > 0 and v_von_nachher = 0 then
        if not exists (select 1 from leermeldungen
                       where artikelnummer = p_artikelnummer and lagerplatz = p_von and gesehen = 0) then
            insert into leermeldungen (zeitstempel, artikelnummer, artikelname, gtin, lagerplatz, gesehen, hinweis)
                values (now(), p_artikelnummer, v_name, v_gtin, p_von, 0, '') on conflict do nothing;
        end if;
    end if;
    if v_nach_nachher > 0 then
        delete from leermeldungen where artikelnummer = p_artikelnummer and lagerplatz = p_nach and gesehen = 0;
    end if;

    insert into buchungen (zeitstempel, typ, artikelnummer, artikelname, gtin, lagerplatz, menge,
        bestand_lp_vorher, bestand_lp_nachher, bestand_gesamt_vorher, bestand_gesamt_nachher, kommentar)
        values (now(), 'Umlagerung', p_artikelnummer, v_name, v_gtin, p_von || ' → ' || p_nach, p_menge,
            v_von_vorher, v_von_nachher, null, null,
            'MOVE|' || json_build_object('artnr', p_artikelnummer, 'von', p_von, 'nach', p_nach, 'menge', p_menge)::text);

    return jsonb_build_object('ok', true,
        'von_nachher', v_von_nachher, 'nach_nachher', v_nach_nachher, 'artikelname', v_name);
end;
$$;

revoke all on function umlagern(text,text,text,integer) from anon, public;
