-- ═══ Unbekannte Artikel (Paket A, Stand 28.09.2026) ══════════════════════════
-- Ablauf im Lager: Eine EAN, die es in LagerPal nicht gibt, wird gescannt
-- (Scanner „Einbuchen" oder „Palette sortieren"). Die App ruft dann
-- unbekannt_einbuchen() auf: Beim ersten Mal wird ein Platzhalter-Artikel
-- angelegt (WE-0-230, WE-0-231, … / „Unbekannt 1", „Unbekannt 2", …, nicht
-- online, Kennzeichen unbekannt = 1), bei jedem weiteren Scan derselben EAN
-- wird nur die Menge erhöht. Gebucht wird immer in den aktuellen
-- Klärfall-Karton „Unbekannt-NN" (keine Palette). „Voll → nächster" legt über
-- unbekannt_karton_naechster() den nächsten Karton an.

-- Aktueller Klärfall-Karton = höchste Nummer (null, wenn noch keiner existiert)
create or replace function unbekannt_karton_aktuell()
returns text language sql stable security definer set search_path = public, pg_temp as $$
    select name from lagerplaetze where name ~ '^Unbekannt-[0-9]+$'
    order by substring(name from '([0-9]+)$')::integer desc limit 1;
$$;
revoke all on function unbekannt_karton_aktuell() from anon, public;
grant execute on function unbekannt_karton_aktuell() to authenticated;

create or replace function unbekannt_einbuchen(
    p_gtin text, p_menge integer, p_kommentar text default '', p_artikelnummer text default ''
) returns jsonb
language plpgsql security definer set search_path = public, pg_temp
as $$
declare
    v_artnr text; v_name text; v_neu boolean := false; v_nr integer; v_karton text; v_res jsonb;
begin
    p_gtin := trim(coalesce(p_gtin,'')); p_artikelnummer := trim(coalesce(p_artikelnummer,''));
    if p_menge is null or p_menge <= 0 then raise exception 'Menge muss eine positive ganze Zahl sein'; end if;
    -- Nummernvergabe und Karton-Wahl nacheinander (zwei Scanner gleichzeitig →
    -- sonst könnten zwei Platzhalter dieselbe Nummer oder dieselbe EAN bekommen)
    perform pg_advisory_xact_lock(hashtext('lagerpal_unbekannt'));

    if p_artikelnummer <> '' then
        -- bereits vorhandener Platzhalter (z. B. Artikelnummer eingetippt)
        select artikelnummer, artikelname into v_artnr, v_name from artikel
            where artikelnummer = p_artikelnummer and unbekannt = 1;
        if not found then raise exception 'Artikel % ist kein unbekannter Artikel', p_artikelnummer; end if;
    else
        -- nur echte EAN/GTIN-Formate (8-14 Ziffern): ein verscannter Karton-
        -- Barcode oder Tippfehler soll keinen Platzhalter erzeugen
        if p_gtin !~ '^[0-9]{8,14}$' then raise exception 'Keine gültige EAN: „%"', p_gtin; end if;
        select artikelnummer, artikelname into v_artnr, v_name from artikel
            where gtin = p_gtin and unbekannt = 1 order by artikelnummer limit 1;
        if not found then
            if exists (select 1 from artikel where gtin = p_gtin or artikelnummer = p_gtin) then
                raise exception 'EAN % gehört zu einem bekannten Artikel', p_gtin;
            end if;
            -- nächste freie Nummer: höchste je vergebene WE-0-Nummer (auch schon
            -- zugeordnete/gelöschte, daher auch im Protokoll suchen) + 1, ab 230
            select greatest(229, coalesce(max(substring(nr from '^WE-0-([0-9]+)$')::integer), 229)) + 1 into v_nr
                from (select artikelnummer as nr from artikel where artikelnummer like 'WE-0-%'
                      union all
                      select artikelnummer from buchungen where artikelnummer like 'WE-0-%') t
                where nr ~ '^WE-0-[0-9]+$';
            v_artnr := 'WE-0-' || v_nr;
            v_name  := 'Unbekannt ' || (v_nr - 229);
            insert into artikel (artikelnummer, artikelname, gtin, ist_set, online, unbekannt)
                values (v_artnr, v_name, p_gtin, 0, 2, 1);
            v_neu := true;
        end if;
    end if;

    v_karton := unbekannt_karton_aktuell();
    if v_karton is null then
        v_karton := 'Unbekannt-01';
        insert into lagerplaetze (name, angelegt, palette, kanal) values (v_karton, now()::text, '', 0)
            on conflict (name) do nothing;
    end if;

    v_res := buchen(v_artnr, v_karton, 'ein', p_menge,
        coalesce(nullif(trim(coalesce(p_kommentar,'')),''), 'Unbekannter Artikel')
        || case when v_neu then ' (neu angelegt)' else '' end);

    return v_res || jsonb_build_object('artikelnummer', v_artnr, 'artikelname', v_name,
        'gtin', p_gtin, 'karton', v_karton, 'neu', v_neu);
end;
$$;
revoke all on function unbekannt_einbuchen(text,integer,text,text) from anon, public;
grant execute on function unbekannt_einbuchen(text,integer,text,text) to authenticated;

-- „Unbekannt-Karton voll → nächster": legt Unbekannt-(NN+1) an
create or replace function unbekannt_karton_naechster()
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare v_akt text; v_nr integer; v_neu text;
begin
    perform pg_advisory_xact_lock(hashtext('lagerpal_unbekannt'));
    v_akt := unbekannt_karton_aktuell();
    -- Doppelklick-Schutz: aus einem leeren Karton wird kein weiterer gemacht
    if v_akt is not null and not exists (select 1 from bestaende where lagerplatz = v_akt and menge > 0) then
        raise exception 'Karton % ist noch leer - kein neuer Karton nötig', v_akt;
    end if;
    v_nr := coalesce(substring(v_akt from '([0-9]+)$')::integer, 0) + 1;
    v_neu := 'Unbekannt-' || lpad(v_nr::text, greatest(2, length(v_nr::text)), '0');   -- ab 100 nicht abschneiden
    insert into lagerplaetze (name, angelegt, palette, kanal) values (v_neu, now()::text, '', 0)
        on conflict (name) do nothing;
    return jsonb_build_object('ok', true, 'alt', v_akt, 'neu', v_neu);
end; $$;
revoke all on function unbekannt_karton_naechster() from anon, public;
grant execute on function unbekannt_karton_naechster() to authenticated;

-- ═══ Neue Artikel aus der JTL-Artikelliste (Stand 28.09.2026) ════════════════
-- Wird beim Scannen (Scanner „Einbuchen", Palette sortieren) aufgerufen, wenn
-- eine EAN in LagerPal nicht bekannt ist. Steht sie GENAU EINMAL in der
-- JTL-Artikelliste, wird der Artikel mit JTL-Nummer und Name angelegt
-- (online = 2 „nicht online", kein Set, nicht unbekannt) und im Protokoll als
-- „Artikel angelegt / Neu angelegt aus JTL-Liste" vermerkt. Die Buchung selbst
-- macht danach die App wie bei jedem normalen Artikel.
-- Nicht in der Liste oder mehrdeutig (12 EANs stehen bei zwei Artikeln)
-- → gefunden = false, die App behandelt den Scan dann als „Unbekannt".
create or replace function artikel_aus_liste(p_gtin text)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare v_n integer; v_row record; v_ex record;
begin
    p_gtin := trim(coalesce(p_gtin,''));
    if p_gtin !~ '^[0-9]{8,14}$' then
        return jsonb_build_object('gefunden', false, 'grund', 'keine EAN');
    end if;
    perform pg_advisory_xact_lock(hashtext('lagerpal_unbekannt'));
    if exists (select 1 from artikel where gtin = p_gtin) then
        return jsonb_build_object('gefunden', false, 'grund', 'EAN in LagerPal bekannt');
    end if;
    select count(*) into v_n from jtl_artikelliste where gtin = p_gtin;
    if v_n = 0 then return jsonb_build_object('gefunden', false, 'grund', 'nicht in Liste'); end if;
    if v_n > 1 then return jsonb_build_object('gefunden', false, 'grund', 'mehrdeutig', 'anzahl', v_n); end if;
    select artikelnummer, artikelname, gtin into v_row from jtl_artikelliste where gtin = p_gtin;
    -- Nummer gibt es in LagerPal schon (dort ohne/mit anderer EAN) → diesen nehmen, nichts ändern
    select artikelnummer, artikelname, online, ist_set, unbekannt into v_ex from artikel where artikelnummer = v_row.artikelnummer;
    if found then
        return jsonb_build_object('gefunden', true, 'neu', false, 'artikelnummer', v_ex.artikelnummer,
            'artikelname', v_ex.artikelname, 'gtin', p_gtin, 'online', v_ex.online, 'ist_set', v_ex.ist_set, 'unbekannt', v_ex.unbekannt);
    end if;
    insert into artikel (artikelnummer, artikelname, gtin, ist_set, online, unbekannt)
        values (v_row.artikelnummer, coalesce(nullif(v_row.artikelname,''), v_row.artikelnummer), p_gtin, 0, 2, 0);
    insert into buchungen (zeitstempel, typ, artikelnummer, artikelname, gtin, lagerplatz, menge, kommentar)
        values (now(), 'Artikel angelegt', v_row.artikelnummer, coalesce(nullif(v_row.artikelname,''), v_row.artikelnummer), p_gtin, '—', null,
                'Neu angelegt aus JTL-Liste (Scan)');
    return jsonb_build_object('gefunden', true, 'neu', true, 'artikelnummer', v_row.artikelnummer,
        'artikelname', coalesce(nullif(v_row.artikelname,''), v_row.artikelnummer), 'gtin', p_gtin, 'online', 2, 'ist_set', 0, 'unbekannt', 0);
end; $$;
revoke all on function artikel_aus_liste(text) from anon, public;
grant execute on function artikel_aus_liste(text) to authenticated;


-- ─── Abschnitt: 08_paletten.sql ───
-- Einmalig im Supabase SQL-Editor ausführen.
--
-- Ersetzt die bisher im Code fest hinterlegte Liste "P01..P40" (nur in
-- "Palette sortieren" sichtbar, nirgends verwaltbar) durch eine echte,
-- editierbare Palettenliste. Nichts Bestehendes geht verloren: die Tabelle
-- wird beim ersten Lauf mit P01..P40 UND allen Paletten-Werten befüllt, die
-- schon bei Lagerplätzen/Kartons eingetragen sind.

-- ── Tabelle ──────────────────────────────────────────────────────────────────
create table if not exists paletten (
    name     text primary key,
    erstellt timestamptz not null default now()
);

