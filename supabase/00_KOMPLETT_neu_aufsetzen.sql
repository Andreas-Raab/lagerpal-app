-- ── Artikel bearbeiten (Name/GTIN/Set/Online) ────────────────────────────────
create or replace function artikel_bearbeiten(
    p_artikelnummer text, p_artikelname text, p_gtin text, p_ist_set integer, p_online integer
) returns jsonb
language plpgsql security definer set search_path = public, pg_temp
as $$
declare v_alt record; v_reversal text; v_set integer; v_on integer;
begin
    p_artikelname := trim(p_artikelname); p_gtin := trim(coalesce(p_gtin,''));
    v_set := case when p_ist_set = 1 then 1 else 0 end;
    v_on  := case when coalesce(p_online,0) in (0,1,2) then p_online else 0 end;
    if p_artikelname = '' then raise exception 'Artikelname ist Pflicht'; end if;
    select artikelname, gtin, ist_set, online into v_alt from artikel where artikelnummer = p_artikelnummer;
    if not found then raise exception 'Artikel % nicht gefunden', p_artikelnummer; end if;
    -- Eine GTIN darf zu mehreren Artikeln gehören (siehe artikel_neu) - keine Blockade mehr.
    if p_artikelname = coalesce(v_alt.artikelname,'') and p_gtin = coalesce(v_alt.gtin,'')
       and v_set = coalesce(v_alt.ist_set,0) and v_on = coalesce(v_alt.online,0) then
        return jsonb_build_object('ok', true, 'unveraendert', true);
    end if;
    v_reversal := 'ARTEDIT|' || json_build_object(
        'alt', json_build_object('name', coalesce(v_alt.artikelname,''), 'gtin', coalesce(v_alt.gtin,''), 'ist_set', coalesce(v_alt.ist_set,0), 'online', coalesce(v_alt.online,0)),
        'neu', json_build_object('name', p_artikelname, 'gtin', p_gtin, 'ist_set', v_set, 'online', v_on))::text;
    update artikel set artikelname = p_artikelname, gtin = p_gtin, ist_set = v_set, online = v_on
        where artikelnummer = p_artikelnummer;
    insert into buchungen (zeitstempel, typ, artikelnummer, artikelname, gtin, lagerplatz, menge,
        bestand_lp_vorher, bestand_lp_nachher, bestand_gesamt_vorher, bestand_gesamt_nachher, kommentar)
        values (now(), 'Artikeländerung', p_artikelnummer, p_artikelname, p_gtin, '—', null, null, null, null, null, v_reversal);
    return jsonb_build_object('ok', true);
end;
$$;
